-- =====================================================================
-- ComplaintBox — Full MySQL Schema + Seed Data
-- Charset: utf8mb4 / Engine: InnoDB / Normalized to 3NF (BCNF where noted)
-- =====================================================================


-- Create and select the database
CREATE DATABASE IF NOT EXISTS `complaintbox`
    DEFAULT CHARACTER SET utf8mb4
    COLLATE utf8mb4_unicode_ci;

USE `complaintbox`;

SET FOREIGN_KEY_CHECKS = 0;
SET SQL_MODE = "NO_AUTO_VALUE_ON_ZERO";
SET time_zone = "+06:00"; -- Bangladesh Standard Time

-- =====================================================================
-- DROP TABLES IN REVERSE DEPENDENCY ORDER
-- =====================================================================
DROP TABLE IF EXISTS site_settings;
DROP TABLE IF EXISTS activity_log;
DROP TABLE IF EXISTS feedback_messages;
DROP TABLE IF EXISTS reports;
DROP TABLE IF EXISTS notifications;
DROP TABLE IF EXISTS complaint_ratings;
DROP TABLE IF EXISTS comments;
DROP TABLE IF EXISTS upvotes;
DROP TABLE IF EXISTS complaint_assignments;
DROP TABLE IF EXISTS complaint_status_history;
DROP TABLE IF EXISTS complaint_media;
DROP TABLE IF EXISTS complaint_categories;
DROP TABLE IF EXISTS complaints;
DROP TABLE IF EXISTS department_staff;
DROP TABLE IF EXISTS users;
DROP TABLE IF EXISTS departments;
DROP TABLE IF EXISTS areas;
DROP TABLE IF EXISTS ashon_numbers;
DROP TABLE IF EXISTS districts;

SET FOREIGN_KEY_CHECKS = 1;

-- =====================================================================
-- 1) DISTRICTS — 64 districts of Bangladesh with division
-- =====================================================================
CREATE TABLE districts (
    id        INT AUTO_INCREMENT PRIMARY KEY,
    name      VARCHAR(100) NOT NULL UNIQUE,
    division  VARCHAR(100),
    INDEX idx_district_name (name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =====================================================================
-- 2) ASHON NUMBERS — Constituency codes per district (Dhaka-01, etc.)
-- =====================================================================
CREATE TABLE ashon_numbers (
    id           INT AUTO_INCREMENT PRIMARY KEY,
    district_id  INT NOT NULL,
    ashon_code   VARCHAR(50) NOT NULL,
    INDEX idx_ashon_district (district_id),
    INDEX idx_ashon_code (ashon_code),
    CONSTRAINT fk_ashon_district FOREIGN KEY (district_id) REFERENCES districts(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =====================================================================
-- 3) AREAS — Wards / neighborhoods belonging to each ashon
-- 2NF: name depends only on ashon_id (not directly on district)
-- =====================================================================
CREATE TABLE areas (
    id        INT AUTO_INCREMENT PRIMARY KEY,
    ashon_id  INT NOT NULL,
    name      VARCHAR(150) NOT NULL,
    INDEX idx_area_ashon (ashon_id),
    INDEX idx_area_name (name),
    CONSTRAINT fk_area_ashon FOREIGN KEY (ashon_id) REFERENCES ashon_numbers(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =====================================================================
-- 4) DEPARTMENTS — Government departments
-- =====================================================================
CREATE TABLE departments (
    id            INT AUTO_INCREMENT PRIMARY KEY,
    name          VARCHAR(150) NOT NULL UNIQUE,
    category_key  VARCHAR(100) NOT NULL,
    contact_email VARCHAR(255),
    contact_phone VARCHAR(30),
    description   TEXT,
    icon          VARCHAR(100),
    created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_dept_cat (category_key)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =====================================================================
-- 5) USERS — Citizens + admin accounts
-- 3NF: stores district_id/ashon_id/area_id as FKs (no name duplication)
-- =====================================================================
CREATE TABLE users (
    id                 INT AUTO_INCREMENT PRIMARY KEY,
    user_uid           VARCHAR(20) NOT NULL UNIQUE,
    full_name          VARCHAR(200) NOT NULL,
    username           VARCHAR(100) UNIQUE,
    email              VARCHAR(255) UNIQUE,
    phone              VARCHAR(20) NOT NULL UNIQUE,
    nid_number         VARCHAR(50) UNIQUE,
    nid_front_image    VARCHAR(500),
    nid_back_image     VARCHAR(500),
    profile_picture    VARCHAR(500),
    password_hash      VARCHAR(500) NOT NULL,
    district_id        INT,
    ashon_id           INT,
    area_id            INT,
    role               ENUM('citizen','admin') DEFAULT 'citizen',
    profile_verified   ENUM('pending','verified') DEFAULT 'pending',
    is_banned          TINYINT(1) DEFAULT 0,
    is_deleted         TINYINT(1) DEFAULT 0,
    created_at         TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at         TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_user_uid (user_uid),
    INDEX idx_user_email (email),
    INDEX idx_user_phone (phone),
    INDEX idx_user_nid (nid_number),
    INDEX idx_user_district (district_id),
    INDEX idx_user_role (role),
    INDEX idx_user_verified (profile_verified),
    CONSTRAINT fk_user_district FOREIGN KEY (district_id) REFERENCES districts(id) ON DELETE SET NULL,
    CONSTRAINT fk_user_ashon FOREIGN KEY (ashon_id) REFERENCES ashon_numbers(id) ON DELETE SET NULL,
    CONSTRAINT fk_user_area FOREIGN KEY (area_id) REFERENCES areas(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =====================================================================
-- 6) DEPARTMENT STAFF — Staff accounts mapped to departments
-- =====================================================================
CREATE TABLE department_staff (
    id              INT AUTO_INCREMENT PRIMARY KEY,
    staff_uid       VARCHAR(20) NOT NULL UNIQUE,
    id_card_number  VARCHAR(100) NOT NULL UNIQUE,
    full_name       VARCHAR(200) NOT NULL,
    email           VARCHAR(255) NOT NULL UNIQUE,
    phone           VARCHAR(20) NOT NULL,
    nid_number      VARCHAR(50),
    password_hash   VARCHAR(500) NOT NULL,
    department_id   INT NOT NULL,
    designation     VARCHAR(150) NOT NULL,
    profile_picture VARCHAR(500),
    district_id     INT,
    ashon_id        INT,
    work_status     ENUM('active','on_leave') DEFAULT 'active',
    is_deleted      TINYINT(1) DEFAULT 0,
    joined_date     DATE,
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_staff_uid (staff_uid),
    INDEX idx_staff_idcard (id_card_number),
    INDEX idx_staff_dept (department_id),
    INDEX idx_staff_email (email),
    INDEX idx_staff_status (work_status),
    CONSTRAINT fk_staff_dept FOREIGN KEY (department_id) REFERENCES departments(id),
    CONSTRAINT fk_staff_district FOREIGN KEY (district_id) REFERENCES districts(id) ON DELETE SET NULL,
    CONSTRAINT fk_staff_ashon FOREIGN KEY (ashon_id) REFERENCES ashon_numbers(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =====================================================================
-- 7) COMPLAINTS — Main complaint records
-- =====================================================================
CREATE TABLE complaints (
    id                      INT AUTO_INCREMENT PRIMARY KEY,
    complaint_id            VARCHAR(20) NOT NULL UNIQUE,
    submitted_by_user_id    INT NOT NULL,
    subject                 VARCHAR(500) NOT NULL,
    description             TEXT NOT NULL,
    priority                ENUM('low','medium','high','critical') NOT NULL,
    status                  ENUM('submitted','pending','in_review','assigned','in_progress','resolved','rejected') DEFAULT 'submitted',
    district_id             INT NOT NULL,
    ashon_id                INT NOT NULL,
    area_id                 INT,
    map_lat                 DECIMAL(10,7),
    map_lng                 DECIMAL(10,7),
    map_address             TEXT,
    assigned_department_id  INT,
    assigned_by_admin       TINYINT(1) DEFAULT 0,
    auto_assigned           TINYINT(1) DEFAULT 0,
    is_approved             TINYINT(1) DEFAULT 0,
    approval_status         ENUM('pending','approved','rejected') DEFAULT 'pending',
    rejection_reason        TEXT,
    rejected_complaint_ref  VARCHAR(20),
    is_deleted              TINYINT(1) DEFAULT 0,
    upvote_count            INT DEFAULT 0,
    comment_count           INT DEFAULT 0,
    is_featured             TINYINT(1) DEFAULT 0,
    submitted_at            TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    approved_at             TIMESTAMP NULL,
    resolved_at             TIMESTAMP NULL,
    INDEX idx_cmp_cmpid (complaint_id),
    INDEX idx_cmp_user (submitted_by_user_id),
    INDEX idx_cmp_status (status),
    INDEX idx_cmp_approval (approval_status),
    INDEX idx_cmp_district (district_id),
    INDEX idx_cmp_ashon (ashon_id),
    INDEX idx_cmp_dept (assigned_department_id),
    INDEX idx_cmp_priority (priority),
    INDEX idx_cmp_submitted (submitted_at),
    INDEX idx_cmp_upvote (upvote_count),
    INDEX idx_cmp_approved (is_approved),
    INDEX idx_cmp_featured (is_featured),
    INDEX idx_cmp_district_status (district_id, status),
    INDEX idx_cmp_status_priority (status, priority),
    INDEX idx_cmp_approval_deleted (approval_status, is_deleted),
    CONSTRAINT fk_cmp_user FOREIGN KEY (submitted_by_user_id) REFERENCES users(id),
    CONSTRAINT fk_cmp_district FOREIGN KEY (district_id) REFERENCES districts(id),
    CONSTRAINT fk_cmp_ashon FOREIGN KEY (ashon_id) REFERENCES ashon_numbers(id),
    CONSTRAINT fk_cmp_area FOREIGN KEY (area_id) REFERENCES areas(id) ON DELETE SET NULL,
    CONSTRAINT fk_cmp_dept FOREIGN KEY (assigned_department_id) REFERENCES departments(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =====================================================================
-- 8) COMPLAINT CATEGORIES — Many-to-many (each complaint can have multiple)
-- 1NF: avoids comma-separated values in complaints table
-- =====================================================================
CREATE TABLE complaint_categories (
    id            INT AUTO_INCREMENT PRIMARY KEY,
    complaint_id  INT NOT NULL,
    category      ENUM('infrastructure','water_service','electricity','waste_management','traffic_transport','environment','public_services','others') NOT NULL,
    INDEX idx_cc_complaint (complaint_id),
    INDEX idx_cc_category (category),
    INDEX idx_cc_cmp_cat (complaint_id, category),
    CONSTRAINT fk_cc_complaint FOREIGN KEY (complaint_id) REFERENCES complaints(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =====================================================================
-- 9) COMPLAINT MEDIA — Citizen photos/videos + staff resolution proofs
-- =====================================================================
CREATE TABLE complaint_media (
    id            INT AUTO_INCREMENT PRIMARY KEY,
    complaint_id  INT NOT NULL,
    file_path     VARCHAR(500) NOT NULL,
    file_type     ENUM('image','video') NOT NULL,
    uploaded_by   ENUM('citizen','staff') DEFAULT 'citizen',
    is_proof      TINYINT(1) DEFAULT 0,
    created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_cm_complaint (complaint_id),
    INDEX idx_cm_proof (is_proof),
    CONSTRAINT fk_cm_complaint FOREIGN KEY (complaint_id) REFERENCES complaints(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =====================================================================
-- 10) COMPLAINT STATUS HISTORY — Status transitions audit trail
-- =====================================================================
CREATE TABLE complaint_status_history (
    id              INT AUTO_INCREMENT PRIMARY KEY,
    complaint_id    INT NOT NULL,
    status          ENUM('submitted','pending','in_review','assigned','in_progress','resolved','rejected') NOT NULL,
    changed_by_type ENUM('citizen','staff','admin') NOT NULL,
    changed_by_id   INT NOT NULL,
    notes           TEXT,
    changed_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_csh_complaint (complaint_id),
    INDEX idx_csh_changed (changed_at),
    CONSTRAINT fk_csh_complaint FOREIGN KEY (complaint_id) REFERENCES complaints(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =====================================================================
-- 11) COMPLAINT ASSIGNMENTS — Complaint ↔ staff member assignments
-- =====================================================================
CREATE TABLE complaint_assignments (
    id                INT AUTO_INCREMENT PRIMARY KEY,
    complaint_id      INT NOT NULL,
    staff_id          INT NOT NULL,
    assigned_by_type  ENUM('admin','staff') NOT NULL,
    assigned_by_id    INT NOT NULL,
    assigned_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    removed_at        TIMESTAMP NULL,
    is_active         TINYINT(1) DEFAULT 1,
    INDEX idx_ca_complaint (complaint_id),
    INDEX idx_ca_staff (staff_id),
    INDEX idx_ca_active (is_active),
    CONSTRAINT fk_ca_complaint FOREIGN KEY (complaint_id) REFERENCES complaints(id) ON DELETE CASCADE,
    CONSTRAINT fk_ca_staff FOREIGN KEY (staff_id) REFERENCES department_staff(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =====================================================================
-- 12) UPVOTES — BCNF: composite UNIQUE prevents duplicate upvotes
-- =====================================================================
CREATE TABLE upvotes (
    id            INT AUTO_INCREMENT PRIMARY KEY,
    complaint_id  INT NOT NULL,
    user_id       INT NOT NULL,
    created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uq_upvote (complaint_id, user_id),
    INDEX idx_up_complaint (complaint_id),
    INDEX idx_up_user (user_id),
    CONSTRAINT fk_up_complaint FOREIGN KEY (complaint_id) REFERENCES complaints(id) ON DELETE CASCADE,
    CONSTRAINT fk_up_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =====================================================================
-- 13) COMMENTS — Public discussion on complaints
-- =====================================================================
CREATE TABLE comments (
    id            INT AUTO_INCREMENT PRIMARY KEY,
    complaint_id  INT NOT NULL,
    user_id       INT NOT NULL,
    comment_text  TEXT NOT NULL,
    is_edited     TINYINT(1) DEFAULT 0,
    is_deleted    TINYINT(1) DEFAULT 0,
    created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_cm_complaint (complaint_id),
    INDEX idx_cm_user (user_id),
    INDEX idx_cm_created (created_at),
    CONSTRAINT fk_comment_complaint FOREIGN KEY (complaint_id) REFERENCES complaints(id) ON DELETE CASCADE,
    CONSTRAINT fk_comment_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =====================================================================
-- 14) COMPLAINT RATINGS — BCNF: one rating per complaint (UNIQUE)
-- =====================================================================
CREATE TABLE complaint_ratings (
    id            INT AUTO_INCREMENT PRIMARY KEY,
    complaint_id  INT NOT NULL UNIQUE,
    user_id       INT NOT NULL,
    rating        TINYINT NOT NULL,
    created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_cr_complaint (complaint_id),
    CONSTRAINT chk_rating CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT fk_cr_complaint FOREIGN KEY (complaint_id) REFERENCES complaints(id) ON DELETE CASCADE,
    CONSTRAINT fk_cr_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =====================================================================
-- 15) NOTIFICATIONS — In-app notifications (citizen + staff)
-- =====================================================================
CREATE TABLE notifications (
    id                    INT AUTO_INCREMENT PRIMARY KEY,
    recipient_type        ENUM('citizen','staff') NOT NULL,
    recipient_id          INT NOT NULL,
    type                  ENUM('complaint_update','admin_message','comment','upvote','profile_update','system') NOT NULL,
    title                 VARCHAR(300) NOT NULL,
    message               TEXT NOT NULL,
    related_complaint_id  INT NULL,
    is_read               TINYINT(1) DEFAULT 0,
    created_at            TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_n_recipient (recipient_type, recipient_id),
    INDEX idx_n_read (is_read),
    INDEX idx_n_type (type),
    INDEX idx_n_created (created_at),
    INDEX idx_n_recipient_read (recipient_type, recipient_id, is_read),
    CONSTRAINT fk_n_complaint FOREIGN KEY (related_complaint_id) REFERENCES complaints(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =====================================================================
-- 16) REPORTS — Abuse / staff / technical reports
-- =====================================================================
CREATE TABLE reports (
    id            INT AUTO_INCREMENT PRIMARY KEY,
    reporter_type ENUM('citizen','staff') NOT NULL,
    reporter_id   INT NOT NULL,
    topic         VARCHAR(300) NOT NULL,
    description   TEXT NOT NULL,
    category      ENUM('fake_complaint','fake_user','fake_comment','technical_issue','department_staff','add_new_staff') NOT NULL,
    related_id    INT NULL,
    image_paths   JSON,
    admin_reply   TEXT,
    status        ENUM('pending','reviewed') DEFAULT 'pending',
    created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_rep_type (reporter_type),
    INDEX idx_rep_cat (category),
    INDEX idx_rep_status (status),
    INDEX idx_rep_created (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =====================================================================
-- 17) FEEDBACK MESSAGES — Citizen testimonials / feedback
-- =====================================================================
CREATE TABLE feedback_messages (
    id           INT AUTO_INCREMENT PRIMARY KEY,
    user_id      INT NOT NULL,
    topic        VARCHAR(300) NOT NULL,
    rating       TINYINT NOT NULL,
    message      TEXT NOT NULL,
    is_featured  TINYINT(1) DEFAULT 0,
    is_deleted   TINYINT(1) DEFAULT 0,
    created_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_fb_featured (is_featured),
    INDEX idx_fb_rating (rating),
    INDEX idx_fb_user (user_id),
    CONSTRAINT chk_fb_rating CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT fk_fb_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =====================================================================
-- 18) ACTIVITY LOG — Audit trail of major actions
-- =====================================================================
CREATE TABLE activity_log (
    id                   INT AUTO_INCREMENT PRIMARY KEY,
    actor_type           ENUM('citizen','staff','admin','system') NOT NULL,
    actor_id             INT NOT NULL,
    action               VARCHAR(300) NOT NULL,
    related_complaint_id INT NULL,
    related_user_id      INT NULL,
    created_at           TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_al_actor_type (actor_type),
    INDEX idx_al_actor_id (actor_id),
    INDEX idx_al_created (created_at),
    INDEX idx_al_complaint (related_complaint_id),
    INDEX idx_al_actor_created (actor_type, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =====================================================================
-- 19) SITE SETTINGS — Key/value app configuration
-- =====================================================================
CREATE TABLE site_settings (
    id            INT AUTO_INCREMENT PRIMARY KEY,
    setting_key   VARCHAR(100) NOT NULL UNIQUE,
    setting_value TEXT,
    updated_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

